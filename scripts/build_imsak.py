def build_one(info: dict) -> dict:
    return {
        "schema_version": "1.0",
        "title": f"Jadwal Imsakiyah Ramadan {info['hijri']} / {info['year']} M di Kota {info['city']}",
        "city": info["city"],
        "province": info["province"],
        "year": info["year"],
        "hijri": info["hijri"],
        "timezone": info["timezone"],
        "source": "Bimas Islam Kementerian Agama RI (bimasislam.kemenag.go.id)",
        "updated_at": "2026-09-12T00:00:00Z",
        "schedule": _to_schedule(info["rows"]),
    }


def main() -> None:
    for info in _CITIES:
        data = build_one(info)
        slug = f"{info['city'].lower()}-{info['year']}.json"
        targets = [ROOT / "data" / "imsak" / slug, ROOT / "src" / "hapilibur" / "data" / slug]
        for target in targets:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)} ({len(data['schedule'])} hari)")


if __name__ == "__main__":
    main()