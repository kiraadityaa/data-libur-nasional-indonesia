def _to_schedule(rows: list[tuple]) -> list[dict]:
    schedule = []
    for day, y, m, d, imsak, subuh, zuhur, ashar, magrib, isya in rows:
        date = datetime.date(y, m, d).isoformat()
        schedule.append(
            {
                "day": day,
                "date": date,
                "imsak": imsak,
                "subuh": subuh,
                "zuhur": zuhur,
                "ashar": ashar,
                "magrib": magrib,
                "isya": isya,
            }
        )
    return schedule


